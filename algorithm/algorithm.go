// Package algorithm holds keyforge's algorithm registry: the identifiers
// written in envelopes, their exact names, and the construction of the
// primitive for each.
//
// Every protection of stored data and keys goes through an algorithm from
// this registry. The set is compiled in; configuration can narrow it and
// cannot add to it. Adding an algorithm is a release with a new identifier
// and known-answer vectors.
//
// The registry currently holds AES-256-GCM only.
package algorithm

import (
	"crypto/aes"
	"crypto/cipher"
	"errors"
	"fmt"
)

// ID is an algorithm identifier as written in the envelope header.
type ID uint8

const (
	// AES256GCM is AES-256-GCM with a random 96-bit nonce generated by
	// [cipher.NewGCMWithRandomNonce], the only GCM constructor permitted
	// under GODEBUG=fips140=only.
	AES256GCM ID = 1
)

var (
	// ErrUnknown is returned for an identifier that is not in the registry.
	ErrUnknown = errors.New("algorithm: unknown algorithm")
	// ErrKeySize is returned when a key does not have the size the algorithm
	// requires.
	ErrKeySize = errors.New("algorithm: wrong key size")
)

type spec struct {
	name      string
	keySize   int
	nonceSize int
	tagSize   int
}

func lookup(id ID) (spec, bool) {
	switch id {
	case AES256GCM:
		return spec{name: "AES-256-GCM", keySize: 32, nonceSize: 12, tagSize: 16}, true
	default:
		return spec{}, false
	}
}

// Valid reports whether id is in the registry.
func (id ID) Valid() bool {
	_, ok := lookup(id)
	return ok
}

// String returns the algorithm's exact name, mode and size included, or a
// placeholder for an identifier that is not in the registry.
func (id ID) String() string {
	if s, ok := lookup(id); ok {
		return s.name
	}
	return fmt.Sprintf("unknown(%d)", uint8(id))
}

// KeySize returns the key size in bytes, or 0 for an unknown identifier.
func (id ID) KeySize() int {
	s, _ := lookup(id)
	return s.keySize
}

// NonceSize returns the size in bytes of the nonce stored in the envelope
// header, or 0 for an unknown identifier.
func (id ID) NonceSize() int {
	s, _ := lookup(id)
	return s.nonceSize
}

// TagSize returns the size in bytes of the authentication tag, or 0 for an
// unknown identifier.
func (id ID) TagSize() int {
	s, _ := lookup(id)
	return s.tagSize
}

// New returns the AEAD for id keyed with key. The AEAD generates a random
// nonce on Seal and prepends it to the ciphertext, and its NonceSize is zero.
// The cipher keeps its own expanded copy of the key; the caller keeps
// ownership of key and should zero it when done.
func New(id ID, key []byte) (cipher.AEAD, error) {
	s, ok := lookup(id)
	if !ok {
		return nil, fmt.Errorf("%w: %d", ErrUnknown, uint8(id))
	}
	if len(key) != s.keySize {
		return nil, fmt.Errorf("%w: %s requires %d bytes, got %d", ErrKeySize, s.name, s.keySize, len(key))
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("algorithm: %s: %w", s.name, err)
	}
	aead, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, fmt.Errorf("algorithm: %s: %w", s.name, err)
	}
	return aead, nil
}
