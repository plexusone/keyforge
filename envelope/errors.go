package envelope

import (
	"errors"
	"fmt"
)

// Typed errors. Callers match them with [errors.Is]. Errors that carry the
// offending value are [*ValueError]; use [errors.As] to read it.
var (
	// ErrBadMagic is returned when the input does not begin with "KF".
	ErrBadMagic = errors.New("envelope: bad magic")
	// ErrTruncated is returned when the input ends before the structure it
	// describes.
	ErrTruncated = errors.New("envelope: truncated input")
	// ErrUnsupportedFormat is returned for a format version this build does
	// not implement.
	ErrUnsupportedFormat = errors.New("envelope: unsupported format version")
	// ErrUnknownMode is returned for a mode this build does not implement.
	ErrUnknownMode = errors.New("envelope: unknown mode")
	// ErrUnknownAlgorithm is returned for an algorithm identifier that is not
	// in the registry.
	ErrUnknownAlgorithm = errors.New("envelope: unknown algorithm")
	// ErrUnsupportedFlags is returned when any flag bit is set. All bits are
	// reserved in format 1 and every bit assigned later is critical.
	ErrUnsupportedFlags = errors.New("envelope: unsupported flags")
	// ErrInvalidPurpose is returned for an empty or malformed purpose name.
	ErrInvalidPurpose = errors.New("envelope: invalid purpose")
	// ErrInvalidHeader is returned when a header's fields are inconsistent
	// with its mode.
	ErrInvalidHeader = errors.New("envelope: invalid header")
	// ErrBadTextForm is returned when text input does not have the
	// "kf<version>." prefix or is not valid unpadded base64url.
	ErrBadTextForm = errors.New("envelope: bad text form")
	// ErrAuthentication is returned when the payload does not authenticate:
	// a wrong key, a changed header or context, or a modified ciphertext.
	// It deliberately carries no further detail.
	ErrAuthentication = errors.New("envelope: authentication failed")
	// ErrNotRandomNonce is returned when Seal or Open is given an AEAD that
	// takes an explicit nonce. The format stores a random nonce generated by
	// the AEAD, and nothing else is accepted.
	ErrNotRandomNonce = errors.New("envelope: AEAD must generate its own nonce")
)

// ValueError is a typed error that carries the offending value, for example
// the format version that was not recognized.
type ValueError struct {
	Kind  error
	Value uint8
}

// Error implements error.
func (e *ValueError) Error() string {
	return fmt.Sprintf("%v: %d", e.Kind, e.Value)
}

// Unwrap lets [errors.Is] match the sentinel in Kind.
func (e *ValueError) Unwrap() error { return e.Kind }
